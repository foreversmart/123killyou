package session

import (
	"context"
	"nightwatch/internal/game"
	"time"
)

type audioKey struct{ SessionID, RunID, RequestID string }
type cachedAudio struct {
	Audio   DialogueAudio
	Created time.Time
}

func validAudio(audio DialogueAudio) bool {
	return len(audio.PCM) > 0 && len(audio.PCM)%2 == 0 && len(audio.PCM) <= 2<<20 && (audio.SampleRate == 16000 || audio.SampleRate == 24000)
}

func (s *Service) cacheAudio(key audioKey, audio DialogueAudio) {
	s.audioMu.Lock()
	defer s.audioMu.Unlock()
	if s.audio == nil {
		s.audio = make(map[audioKey]cachedAudio)
	}
	now := time.Now()
	bytes := 0
	for key, value := range s.audio {
		if now.Sub(value.Created) > 10*time.Minute {
			delete(s.audio, key)
		} else {
			bytes += len(value.Audio.PCM)
		}
	}
	for bytes+len(audio.PCM) > 16<<20 || len(s.audio) >= 16 {
		var oldest audioKey
		var created time.Time
		for key, value := range s.audio {
			if created.IsZero() || value.Created.Before(created) {
				oldest, created = key, value.Created
			}
		}
		bytes -= len(s.audio[oldest].Audio.PCM)
		delete(s.audio, oldest)
	}
	audio.PCM = append([]byte(nil), audio.PCM...)
	s.audio[key] = cachedAudio{audio, now}
}

// Audio is ephemeral and deliberately excluded from checkpoints and SQLite.
// Missing audio can only be regenerated by Linx, never by browser synthesis.
func (s *Service) SpeechAudio(id, runID, requestID string) (DialogueAudio, bool) {
	state, err := s.Snapshot(id)
	if err != nil || state.RunID != runID {
		return DialogueAudio{}, false
	}
	s.audioMu.Lock()
	defer s.audioMu.Unlock()
	key := audioKey{id, runID, requestID}
	value, ok := s.audio[key]
	if !ok || time.Since(value.Created) > 10*time.Minute {
		delete(s.audio, key)
		return DialogueAudio{}, false
	}
	return value.Audio, true
}

func (s *Service) attachSpeech(ctx context.Context, result game.Result, key audioKey, prepared *DialogueAudio) game.Result {
	// Reset/load creates a new branch; its confirmation belongs to that branch.
	key.RunID = result.State.RunID
	if _, found := s.SpeechAudio(key.SessionID, key.RunID, key.RequestID); found {
		result.HasAudio = true
		return result
	}
	if prepared == nil && s.provider != nil {
		audio, err := s.provider.Synthesize(ctx, SpeechRequest{Text: result.Speak, NPCID: result.SpeakerID}, nil)
		if err == nil {
			prepared = &audio
		}
	}
	if prepared == nil || !validAudio(*prepared) {
		result.VoiceError = "操作结果已记录，但灵矽语音生成失败。请稍后再试，勿重复交付道具。"
		return result
	}
	// New input may have moved or reset the game while TTS was generated.
	current, err := s.Snapshot(key.SessionID)
	if err != nil || current.RunID != result.State.RunID || current.Revision != result.State.Revision {
		result.VoiceError = "进度已改变，已取消旧回合的灵矽语音。"
		return result
	}
	s.cacheAudio(key, *prepared)
	result.HasAudio = true
	return result
}
